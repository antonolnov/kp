async def main():
    print("=" * 60)
    print("ТЕСТ: Генерация персонализированного КП")
    print("=" * 60)
    
    print(f"\nТранскрибация: {len(TRANSCRIPT)} символов")
    print("\n--- Отправляем в AI (gpt-4o) ---")
    
    start_time = time.time()
    analysis = await analyze_transcript(TRANSCRIPT)
    ai_time = time.time() - start_time
    
    print(f"\n✅ AI ответил за {ai_time:.1f} секунд")
    print(f"\nКомпания: {analysis.company_name}")
    print(f"Контакт: {analysis.contact_name}, {analysis.contact_role}")
    print(f"Рекрутеров: {analysis.num_recruiters}")
    print(f"Сфера: {analysis.industry}")
    
    print(f"\n--- ДИАГНОЗ ---")
    print(f"Ситуация ({len(analysis.diagnosis_situation)} символов):")
    print(analysis.diagnosis_situation)
    print(f"\nБоли ({len(analysis.diagnosis_pains)} пунктов):")
    for i, pain in enumerate(analysis.diagnosis_pains, 1):
        print(f"  {i}. {pain}")
    
    print(f"\n--- РЕШЕНИЕ ---")
    print(f"Базовый функционал ({len(analysis.solution_base)}):")
    for item in analysis.solution_base:
        print(f"  • {item}")
    print(f"\nИнтеграции ({len(analysis.solution_integrations)}):")
    for item in analysis.solution_integrations:
        print(f"  • {item}")
    print(f"\nАвтоматизация ({len(analysis.solution_automation)}):")
    for item in analysis.solution_automation:
        print(f"  • {item}")
    
    print(f"\n--- ПОЧЕМУ WORKHERE ---")
    print(f"Для рекрутеров ({len(analysis.why_recruiters)}):")
    for item in analysis.why_recruiters:
        print(f"  ✓ {item}")
    print(f"\nДля руководителей ({len(analysis.why_managers)}):")
    for item in analysis.why_managers:
        print(f"  ✓ {item}")
    
    print(f"\n--- КЛЮЧЕВОЙ ПОСЫЛ ---")
    print(analysis.key_message)
    
    # Генерируем PDF
    print("\n--- Генерация PDF ---")
    config = ProposalConfig(
        show_standard=True,
        show_premium=False,
        show_ai_option=False,
        num_recruiters=4
    )
    
    output_path = Path("/workspace/bot/test_output.pdf")
    generate_proposal_pdf(analysis, config, output_path)
    
    print(f"\n✅ PDF создан: {output_path}")
    print(f"   Размер: {output_path.stat().st_size / 1024:.1f} KB")
    print("=" * 60)


if __name__ == "__main__":
    asyncio.run(main())
